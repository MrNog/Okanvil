"""Build Okanvil's Modules/DungeonLoot-Data.lua: every Wrath 5-man's bosses and their drops, normal
and heroic, in the shape of RaidLoot-Data, so the Upgrades page, the boss tooltip and the drop
alert work in dungeons too. Read from AtlasLoot's WotLK tables.
usage: python -I scripts/gen_dungeon_loot.py <AddOns dir> <Okanvil Modules dir>"""
import os, re, sys

addons, okv_dir = sys.argv[1:3]

# AtlasLoot's section -> our key and the zone name GetInstanceInfo() returns
DUNGEONS = [
    ("Utgarde Keep", "uk", "Utgarde Keep"),
    ("The Nexus", "nexus", "The Nexus"),
    ("Azjol-Nerub", "an", "Azjol-Nerub"),
    ("Ahn'kahet: The Old Kingdom", "ok", "Ahn'kahet: The Old Kingdom"),
    ("Drak'Tharon Keep", "dtk", "Drak'Tharon Keep"),
    ("The Violet Hold", "vh", "The Violet Hold"),
    ("Gundrak", "gd", "Gundrak"),
    ("Halls of Stone", "hos", "Halls of Stone"),
    ("Halls of Lightning", "hol", "Halls of Lightning"),
    ("Caverns of Time: Old Stratholme", "cos", "The Culling of Stratholme"),
    ("Utgarde Pinnacle", "up", "Utgarde Pinnacle"),
    ("The Oculus", "oc", "The Oculus"),
    ("Trial of the Champion", "toc5", "Trial of the Champion"),
    ("The Forge of Souls", "fos", "The Forge of Souls"),
    ("Pit of Saron", "pos", "Pit of Saron"),
    ("Halls of Reflection", "hor", "Halls of Reflection"),
]
SECTION = {s: (k, z) for s, k, z in DUNGEONS}

names_src = open(os.path.join(addons, "AtlasLoot", "TableRegister", "loottables.en.lua"), encoding="utf-8-sig").read()
table_name = {}
for key, expr in re.findall(r'AtlasLoot_TableNames\["([^"]+)"\] = \{ (.*?), "[^"]*" \};', names_src):
    parts = re.findall(r'"([^"]*)"', expr)
    table_name[key] = " ".join(p for p in parts if p.strip())

# "#s3#" -> "Shoulder", "#h1#" -> "One-Hand", "#w4#" -> "Dagger"
parse_src = open(os.path.join(addons, "AtlasLoot", "Core", "TextParsing.lua"), encoding="utf-8-sig").read()
token = {t: n for t, n in re.findall(r'gsub\(text, "#([shw]\d+)#", \w+\["([^"]+)"\]\)', parse_src)}

def slot_of(desc):
    toks = re.findall(r'#([shw]\d+)#', desc)
    words = [token[t] for t in toks if t in token]
    return " ".join(words)

# NOT drops worth judging: emblems, the Champion's Seal, Frozen Orbs
SKIP_IDS = {47241, 40752, 40753, 45624, 44990, 43102, 47242, 49426}

entry_re = re.compile(r'\{\s*\d+\s*,\s*(\d+)\s*,\s*"[^"]*"\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"')
dungeons = {}       # key -> [ (boss, { id: [name, slot, set(modes)] }) ] in order
src = os.path.join(addons, "AtlasLoot_WrathoftheLichKing", "wrathofthelichking.lua")
section, table, mode, boss = None, None, None, None
for line in open(src, encoding="utf-8-sig"):
    m = re.match(r'^\s*-{3}\s+(.+?)\s+-{3}\s*$', line)
    if m:
        section = m.group(1).strip()
        table = None
        continue
    m = re.match(r'^\s*AtlasLoot_Data\["([^"]+)"\]', line)
    if m:
        table = m.group(1)
        if section not in SECTION or table.endswith("Trash") or "Trash" in table_name.get(table, ""):
            table = None
            continue
        boss = table_name.get(table) or table_name.get(re.sub(r"HEROIC$", "", table)) or table
        # "Amanitar  ( Heroic )" is the same boss as its normal table; "A  /  B" is fought as two NPCs
        boss = re.sub(r"\s*\(\s*Heroic\s*\)\s*$", "", boss)
        boss = re.sub(r"\s+/\s+", " / ", boss).strip()
        mode = "5h" if table.endswith("HEROIC") else "5n"
        continue
    if not table:
        continue
    m = entry_re.search(line)
    if not m:
        continue
    item, name, desc = int(m.group(1)), m.group(2), m.group(3)
    if item == 0:
        if "#j1#" in name: mode = "5n"
        elif "#j3#" in name: mode = "5h"
        continue
    if item in SKIP_IDS:
        continue
    key = SECTION[section][0]
    bosses = dungeons.setdefault(key, [])
    entry = next((b for b in bosses if b[0] == boss), None)
    if not entry:
        entry = (boss, {})
        bosses.append(entry)
    name = re.sub(r"^=q\d=", "", name)
    it = entry[1].setdefault(item, [name, slot_of(desc), set()])
    it[2].add(mode)

def lua(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = ["-- ============================================================",
       "--  Okanvil -- DungeonLoot-Data: every Wrath 5-man's drops, per boss, normal and heroic.",
       "--  The Upgrades page, the boss tooltip and the drop alert read it beside RaidLoot-Data;",
       "--  `m` is \"5n\", \"5h\" or both.",
       "--  Generated by scripts/gen_dungeon_loot.py from AtlasLoot; regenerate it, do not edit by hand.",
       "-- ============================================================",
       "",
       "-- in the order they are listed, with the zone name GetInstanceInfo() returns",
       "OkanvilDungeons = {"]
for s, k, z in DUNGEONS:
    if k in dungeons:
        out.append(f"\t{{ key = {lua(k)}, name = {lua(z)} }},")
out += ["}", "", "OkanvilDungeonLoot = {"]
items = 0
for s, k, z in DUNGEONS:
    if k not in dungeons:
        continue
    out.append(f"\t{k} = {{")
    for boss, its in dungeons[k]:
        # a boss fought as two NPCs names both, so hovering either one finds it
        npcs = boss.split(" / ")
        extra = (", npcs = { " + ", ".join(lua(n) for n in npcs) + " }") if len(npcs) > 1 else ""
        out.append(f"\t\t{{ boss = {lua(boss)}{extra}, items = {{")
        for item, (name, slot, modes) in its.items():
            m = ",".join(x for x in ("5n", "5h") if x in modes)
            out.append(f"\t\t\t{{ id = {item}, name = {lua(name)}, slot = {lua(slot)}, m = {lua(m)} }},")
            items += 1
        out.append("\t\t} },")
    out.append("\t},")
out.append("}")
open(os.path.join(okv_dir, "DungeonLoot-Data.lua"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(len(dungeons), "dungeons,", sum(len(b) for b in dungeons.values()), "bosses,", items, "items")
missing = [s for s, k, z in DUNGEONS if k not in dungeons]
if missing:
    print("no tables found for:", ", ".join(missing))
