# ---- BiS lists ---------------------------------------------------------------------------
row_re = re.compile(
    r'^Bistooltip_wowtbc_bislists\["([^"]+)"\]\["([^"]+)"\]\["([^"]+)"\]\[(\d+)\] = \{ \["slot_name"\] = "([^"]+)"(.*)\}\s*$',
    re.M)
enh_re = re.compile(r'\[(\d)\] = \{ \["type"\] = "(item|spell|none)", \["id"\] = (\d+)')

def read_lists(name):
    """{(cls, spec, phase): [(idx, slot, ids, enhs)]} from one Bistooltip list file."""
    src = open(os.path.join(bt_dir, name), encoding="utf-8-sig").read()
    found = {}
    for cls, spec, phase, idx, slot, rest in row_re.findall(src):
        # the enchant/gem block by position: [1] the enchant, [2..] the sockets; "none" keeps
        # its place as 0 so the gems stay in their sockets
        enh_part = re.search(r'\["enhs"\] = \{(.*?)\} \}?,', rest)
        found_e = {int(n): (t, int(i)) for n, t, i in enh_re.findall(enh_part.group(1) if enh_part else "")}
        enhs = [found_e.get(n, ("none", 0)) for n in range(1, max(found_e or [0]) + 1)]
        # ranked ids are "[n] = 12345"; the enchant/gem block uses "[n] = { ... }" and is skipped
        ids = [int(v) for _, v in re.findall(r'\[(\d)\] = (\d+)', rest)]
        found.setdefault((cls, spec, phase), []).append((int(idx), slot, ids, enhs))
    return found, src

lists = {}
main, src = read_lists("Bistooltip_wowtbc_bislists.lua")
# The _old file holds PR, T7 and T8 and loads after the main one in Bistooltip's .toc, so its
# phases win where both have them, as they do in game.
old, _ = read_lists("Bistooltip_wowtbc_bislists_old.lua")
merged = dict(main)
merged.update(old)
for (cls, spec, phase), rows_ in merged.items():
    lists.setdefault(cls, {}).setdefault(spec, {})[phase] = rows_
phases = re.search(r'Bistooltip_wowtbc_phases = \{([^}]*)\}', src).group(1)

# A list that names two copies of one raid item (25 normal and 25 heroic) must put the
# higher one first: Bistooltip has the 25 normal Sindragosa's Cruel Claw as the Assassination
# BiS and the heroic at #4. Copies are told apart by RaidLoot-Data's mode; a better copy
# below a worse one swaps places with it.
loot_src = open(os.path.join(okv_dir, "RaidLoot-Data.lua"), encoding="utf-8").read()
copy_of = {int(i): (n, m) for i, n, m in
           re.findall(r'id = (\d+), name = "((?:[^"\\]|\\.)*)",[^}]*?m = "(\w+)"', loot_src)}
MODE_RANK = {"10n": 0, "25n": 1, "10h": 1, "25h": 2}

def heroic_first(ids):
    ids = list(ids)
    for a in range(len(ids)):
        for b in range(a + 1, len(ids)):
            x, y = copy_of.get(ids[a]), copy_of.get(ids[b])
            if x and y and x[0] == y[0] and MODE_RANK[x[1]] < MODE_RANK[y[1]]:
                ids[a], ids[b] = ids[b], ids[a]
    return ids

swapped = 0
for cls in lists:
    for spec in lists[cls]:
        for phase, rows_ in lists[cls][spec].items():
            fixed = []
            for idx, slot, ids, enhs in rows_:
                new = heroic_first(ids)
                swapped += new != ids
                fixed.append((idx, slot, new, enhs))
            lists[cls][spec][phase] = fixed

h2a_src = open(os.path.join(bt_dir, "Bistooltip_horde_to_ali.lua"), encoding="utf-8-sig").read()
h2a = re.findall(r'Bistooltip_horde_to_ali\[(\d+)\] = (\d+);', h2a_src)

out = [MIT, "-- Generated by scripts/gen_data.py, do not edit by hand.",
       "-- ns.BIS[class][spec][phase] = { { slot = \"Finger\", e = { gem/enchant }, id1, id2, ... up to 6 (1 = BiS) }, ... }",
       "-- e: the BiS piece's enchant ([1]) and gems ([2..], one per socket); a positive id is an item,",
       "--    a negative one a spell (an enchant), 0 a socket left empty",
       "local _, ns = ...", "", "ns.BIS_PHASES = {" + phases + "}", "ns.BIS = {"]
rows = 0
for cls in sorted(lists):
    out.append(f'\t["{cls}"] = {{')
    for spec in sorted(lists[cls]):
        out.append(f'\t\t["{spec}"] = {{')
        for phase in sorted(lists[cls][spec]):
            out.append(f'\t\t\t["{phase}"] = {{')
            for idx, slot, ids, enhs in sorted(lists[cls][spec][phase]):
                e = ", ".join(str(-i if t == "spell" else (0 if t == "none" else i)) for t, i in enhs)
                out.append(f'\t\t\t\t{{ slot = "{slot}", e = {{ {e} }}, ' + ", ".join(map(str, ids)) + " },")
                rows += 1
            out.append("\t\t\t},")
        out.append("\t\t},")
    out.append("\t},")
out.append("}")
out.append("")
out.append("-- Horde ToC ids -> the alliance ids the lists use")
out.append("ns.BIS_HORDE_TO_ALI = {")
for h, a in h2a:
    out.append(f"\t[{h}] = {a},")
out.append("}")
print(rows, "rows,", len(h2a), "horde ids,", swapped, "rows with the heroic moved up")

# the lists as globals, plus the spec icons the item tooltip and the BiS lists page draw
# beside each list
icons_src = open(os.path.join(bt_dir, "Bistooltip_classes.lua"), encoding="utf-8-sig").read()
icons = re.search(r'^Bistooltip_spec_icons = \{.*?^\}', icons_src, re.M | re.S).group(0)
icons = icons.replace("Bistooltip_spec_icons", "OkanvilBisIcons").replace("    ", "\t")
okv = "\n".join(out[1:])                       # everything after the MIT block
okv = okv.replace("-- Generated by scripts/gen_data.py, do not edit by hand.",
    "-- Okanvil -- Upgrades BiS data, generated by scripts/gen_bis_data.py from Bistooltip;\n"
    "-- regenerate it, do not edit by hand.", 1)
okv = okv.replace("ns.BIS[class]", "OkanvilBis[class]", 1).replace("local _, ns = ...", "local ns = {}", 1)
okv = (MIT + "\n" + okv + "\n\nOkanvilBis = ns.BIS\nOkanvilBisPhases = ns.BIS_PHASES\n"
       "OkanvilBisHordeToAli = ns.BIS_HORDE_TO_ALI\n\n"
       "-- the spec icon for each list, beside its name on the item tooltip\n" + icons + "\n")
open(os.path.join(okv_dir, "Upgrades-Bis-Data.lua"), "w", encoding="utf-8", newline="\n").write(okv)
print("Upgrades-Bis-Data.lua written")
